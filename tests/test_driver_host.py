"""Build and run the portable driver registry tests with sanitizers."""
import os
import subprocess
import tempfile
import unittest


class DriverHostTest(unittest.TestCase):
    def test_registry(self):
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        with tempfile.TemporaryDirectory() as directory:
            binary = os.path.join(directory, 'test_driver')
            result = subprocess.run(
                ['clang', '-std=c11', '-Wall', '-Wextra', '-Werror', '-O2',
                 '-fsanitize=address,undefined', '-fno-sanitize-recover=all',
                 os.path.join(root, 'tests', 'test_driver.c'), '-o', binary],
                capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            result = subprocess.run([binary], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn('PASS: driver registry', result.stdout)


if __name__ == '__main__':
    unittest.main()
